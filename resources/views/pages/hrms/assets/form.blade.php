<script>
(function() {
    const assetCategoriesData = @json($assetCategories ?? []);
    const currentCustomValues = @json(old('custom_fields', $asset?->custom_field_values ?? []));
    const fieldsFetchUrl = "{{ route('hrms.masters.asset-categories.fields') }}";

    function getElements() {
        return {
            categorySelect: document.getElementById('assetCategorySelect'),
            customSection: document.getElementById('categoryCustomFieldsSection'),
            customTitle: document.getElementById('customFieldsSectionTitle'),
            customBadge: document.getElementById('customFieldsCountBadge'),
            customContainer: document.getElementById('categoryCustomFieldsContainer'),
            promptNotice: document.getElementById('categoryPromptNotice'),
            noFieldsNotice: document.getElementById('categoryNoFieldsNotice'),
            loadingNotice: document.getElementById('categoryLoadingNotice'),
            assignedEmployeeField: document.getElementById('assetAssignedEmployeeGroup'),
            assignedDateGroup: document.getElementById('assetAssignedDateGroup')
        };
    }

    window.handleAssetCategoryChange = function(val) {
        const els = getElements();
        const selectedName = (val || (els.categorySelect ? els.categorySelect.value : '') || '').trim();

        if (!selectedName) {
            if (els.customSection) els.customSection.style.display = 'none';
            if (els.promptNotice) els.promptNotice.style.display = 'flex';
            if (els.noFieldsNotice) els.noFieldsNotice.style.display = 'none';
            if (els.loadingNotice) els.loadingNotice.style.display = 'none';
            if (els.customContainer) els.customContainer.innerHTML = '';
            return;
        }

        if (els.promptNotice) els.promptNotice.style.display = 'none';

        // 1. Try instant match from pre-loaded data
        const localCat = assetCategoriesData.find(c => String(c.name).trim().toLowerCase() === selectedName.toLowerCase());
        let localFields = localCat ? localCat.custom_fields : null;
        if (typeof localFields === 'string') {
            try { localFields = JSON.parse(localFields); } catch(e) { localFields = []; }
        }

        if (Array.isArray(localFields) && localFields.length > 0) {
            renderFields(selectedName, localFields);
        } else if (localCat && Array.isArray(localFields) && localFields.length === 0) {
            // Check with server to see if fields were added recently
            fetchFieldsFromServer(selectedName);
        } else {
            fetchFieldsFromServer(selectedName);
        }
    };

    function fetchFieldsFromServer(categoryName) {
        const els = getElements();
        if (els.loadingNotice) els.loadingNotice.style.display = 'flex';
        if (els.customSection) els.customSection.style.display = 'none';
        if (els.noFieldsNotice) els.noFieldsNotice.style.display = 'none';

        fetch(fieldsFetchUrl + '?name=' + encodeURIComponent(categoryName))
            .then(res => res.json())
            .then(data => {
                if (els.loadingNotice) els.loadingNotice.style.display = 'none';
                const fields = data && Array.isArray(data.fields) ? data.fields : [];
                renderFields(categoryName, fields);
            })
            .catch(err => {
                console.error('Error fetching category fields:', err);
                if (els.loadingNotice) els.loadingNotice.style.display = 'none';
                // Fallback to local data
                const fallbackCat = assetCategoriesData.find(c => String(c.name).trim().toLowerCase() === categoryName.toLowerCase());
                renderFields(categoryName, (fallbackCat && Array.isArray(fallbackCat.custom_fields)) ? fallbackCat.custom_fields : []);
            });
    }

    function renderFields(categoryName, fields) {
        const els = getElements();
        if (!els.customContainer || !els.customSection) return;

        if (!Array.isArray(fields) || fields.length === 0) {
            els.customSection.style.display = 'none';
            if (els.noFieldsNotice) els.noFieldsNotice.style.display = 'block';
            els.customContainer.innerHTML = '';
            return;
        }

        if (els.noFieldsNotice) els.noFieldsNotice.style.display = 'none';
        els.customSection.style.display = 'block';
        if (els.customTitle) els.customTitle.textContent = `${categoryName} — Form Fields`;
        if (els.customBadge) els.customBadge.textContent = `${fields.length} Field${fields.length > 1 ? 's' : ''}`;
        els.customContainer.innerHTML = '';

        fields.forEach(field => {
            const fieldName = field.name || 'field_' + Math.random().toString(36).substr(2, 5);
            const rawVal = currentCustomValues[fieldName] ?? '';
            const isRequired = Boolean(field.required);
            const reqStar = isRequired ? '<span class="eob-label-required">*</span>' : '';
            const reqAttr = isRequired ? 'required' : '';
            const placeholder = field.placeholder || '';

            const group = document.createElement('div');
            group.className = 'eob-group';

            let inputHtml = '';

            switch (field.type) {
                case 'number':
                    inputHtml = `<input type="number" step="any" name="custom_fields[${fieldName}]" class="eob-input" value="${escapeHtml(rawVal)}" placeholder="${escapeHtml(placeholder)}" ${reqAttr}>`;
                    break;

                case 'date':
                    inputHtml = `<input type="date" name="custom_fields[${fieldName}]" class="eob-input" value="${escapeHtml(rawVal)}" ${reqAttr}>`;
                    break;

                case 'select':
                    const opts = Array.isArray(field.options) ? field.options : [];
                    let optionsHtml = `<option value="">Select ${escapeHtml(field.label)}</option>`;
                    opts.forEach(opt => {
                        const optVal = String(opt).trim();
                        const isSelected = String(rawVal).trim() === optVal ? 'selected' : '';
                        optionsHtml += `<option value="${escapeHtml(optVal)}" ${isSelected}>${escapeHtml(optVal)}</option>`;
                    });
                    inputHtml = `<select name="custom_fields[${fieldName}]" class="eob-select" ${reqAttr}>${optionsHtml}</select>`;
                    break;

                case 'checkbox':
                    const cbOpts = Array.isArray(field.options) && field.options.length > 0 ? field.options : null;
                    if (cbOpts) {
                        let cbHtml = '<div style="display:flex; flex-wrap:wrap; gap:10px; margin-top:6px;">';
                        const selectedArray = Array.isArray(rawVal) ? rawVal.map(String) : [String(rawVal)];
                        cbOpts.forEach((opt, idx) => {
                            const optVal = String(opt).trim();
                            const isChecked = selectedArray.includes(optVal) ? 'checked' : '';
                            cbHtml += `
                                <label style="display:inline-flex; align-items:center; gap:6px; font-size:13px; color:#334155; cursor:pointer; background:#fff; padding:6px 12px; border:1px solid #cbd5e1; border-radius:8px;">
                                    <input type="checkbox" name="custom_fields[${fieldName}][]" value="${escapeHtml(optVal)}" ${isChecked}>
                                    <span>${escapeHtml(optVal)}</span>
                                </label>`;
                        });
                        cbHtml += '</div>';
                        inputHtml = cbHtml;
                    } else {
                        const isChecked = Boolean(rawVal) && rawVal != '0' ? 'checked' : '';
                        inputHtml = `
                            <div style="margin-top:6px;">
                                <label style="display:inline-flex; align-items:center; gap:8px; font-size:13px; color:#334155; cursor:pointer; background:#fff; padding:8px 14px; border:1px solid #cbd5e1; border-radius:8px;">
                                    <input type="hidden" name="custom_fields[${fieldName}]" value="0">
                                    <input type="checkbox" name="custom_fields[${fieldName}]" value="1" ${isChecked}>
                                    <span>${escapeHtml(placeholder || 'Yes / Active')}</span>
                                </label>
                            </div>`;
                    }
                    break;

                case 'radio':
                    const radioOpts = Array.isArray(field.options) ? field.options : [];
                    let radioHtml = '<div style="display:flex; flex-wrap:wrap; gap:10px; margin-top:6px;">';
                    radioOpts.forEach((opt, idx) => {
                        const optVal = String(opt).trim();
                        const isChecked = String(rawVal).trim() === optVal ? 'checked' : '';
                        radioHtml += `
                            <label style="display:inline-flex; align-items:center; gap:6px; font-size:13px; color:#334155; cursor:pointer; background:#fff; padding:6px 12px; border:1px solid #cbd5e1; border-radius:8px;">
                                <input type="radio" name="custom_fields[${fieldName}]" value="${escapeHtml(optVal)}" ${isChecked} ${idx === 0 && isRequired ? 'required' : ''}>
                                <span>${escapeHtml(optVal)}</span>
                            </label>`;
                    });
                    radioHtml += '</div>';
                    inputHtml = radioHtml;
                    break;

                case 'file':
                    const hasExistingFile = rawVal && typeof rawVal === 'string' && rawVal.length > 0;
                    let fileNotice = '';
                    if (hasExistingFile) {
                        fileNotice = `
                            <div style="margin-top:4px; font-size:12px;">
                                <a href="/${escapeHtml(rawVal)}" target="_blank" style="color:#0284c7; text-decoration:underline; font-weight:600; display:inline-flex; align-items:center; gap:4px;">
                                    📎 View Current Uploaded File
                                </a>
                                <span style="color:#64748b; font-size:11px;">(Upload new file to replace)</span>
                            </div>`;
                    }
                    inputHtml = `
                        <input type="file" name="custom_files[${fieldName}]" class="eob-input" style="padding:6px 10px;" ${!hasExistingFile && isRequired ? 'required' : ''}>
                        ${fileNotice}`;
                    break;

                case 'text':
                default:
                    inputHtml = `<input type="text" name="custom_fields[${fieldName}]" class="eob-input" value="${escapeHtml(rawVal)}" placeholder="${escapeHtml(placeholder)}" ${reqAttr}>`;
                    break;
            }

            group.innerHTML = `
                <label class="eob-label">${escapeHtml(field.label)} ${reqStar}</label>
                ${inputHtml}
                ${placeholder && field.type !== 'checkbox' ? `<div class="eob-help">${escapeHtml(placeholder)}</div>` : ''}
            `;

            els.customContainer.appendChild(group);
        });
    }

    function escapeHtml(text) {
        if (!text) return '';
        return String(text)
            .replace(/&/g, "&amp;")
            .replace(/</g, "&lt;")
            .replace(/>/g, "&gt;")
            .replace(/"/g, "&quot;")
            .replace(/'/g, "&#039;");
    }

    // Attach listeners across all possible libraries (Select2, jQuery, Native)
    function initListeners() {
        const els = getElements();
        if (els.categorySelect) {
            els.categorySelect.addEventListener('change', function() {
                window.handleAssetCategoryChange(this.value);
            });
        }

        if (window.jQuery) {
            $(document).on('change select2:select select2:clear', '#assetCategorySelect', function(e) {
                const val = $(this).val();
                window.handleAssetCategoryChange(val);
            });
        }

        // Run initial check if category is preselected (e.g., validation redirect or edit)
        if (els.categorySelect && els.categorySelect.value) {
            window.handleAssetCategoryChange(els.categorySelect.value);
        }
    }

    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', initListeners);
    } else {
        initListeners();
    }
})();
</script>
